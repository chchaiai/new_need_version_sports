import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { load } from "js-yaml";
import { build } from "esbuild";

const contractUrl = new URL("../../../contracts/openapi.yaml", import.meta.url);
const outputUrl = new URL("../../frontend/student/js/contract/validators.generated.js", import.meta.url);
const expectedSha = "5c87eeb9bca39585cea2e3c80c60d58813b4367e1a60b161ed8c7f82af4a19ed";
const bytes = await readFile(contractUrl);
const sha = createHash("sha256").update(bytes).digest("hex");
if (sha !== expectedSha) throw new Error("Contract SHA differs from the reviewed Phase 6 input.");
const document = load(bytes.toString("utf8"));
if (document.info.version !== "1.3.0-contract") throw new Error("Unexpected Contract version.");
const id = "urn:bnbu:phase6b:contract";
const ajv = new Ajv2020({
  // OpenAPI annotations are not JSON Schema assertions. Keep all schema assertions,
  // formats and conditional constraints, without mutation/coercion/default insertion.
  strict: false, allErrors: true, validateFormats: true,
  coerceTypes: false, useDefaults: false, removeAdditional: false, ownProperties: true,
  inlineRefs: false, code: { source: true, esm: true, lines: true },
});
addFormats(ajv, { mode: "full" });
ajv.addSchema({ $id: id, components: document.components });
const names = ["ExerciseRecord", "RecordReviewSummary", "PublicReviewReason", "StudentCourseProgress", "StudentCourse"];
const exports = Object.fromEntries(names.map((name) => ["validate" + name, id + "#/components/schemas/" + name]));
const code = standaloneCode(ajv, exports);
const bundle = await build({
  stdin: { contents: code, sourcefile: "phase6b-standalone.js", resolveDir: fileURLToPath(new URL("../", import.meta.url)) },
  bundle: true, write: false, format: "esm", platform: "browser", target: "es2020",
  minify: true, legalComments: "none", charset: "utf8", metafile: true,
});
if (Object.values(bundle.metafile.outputs).some((output) => output.imports.length > 0)) {
  throw new Error("Runtime validator must be self-contained for native browser modules.");
}
const generated = "// GENERATED by scripts/generate-phase6b-validators.mjs; do not edit.\n"
  + "// Contract 1.3.0-contract / RC / SHA-256 " + sha + "\n"
  + bundle.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(outputUrl, "utf8") !== generated) throw new Error("Generated runtime validator is stale.");
  console.log("PASS: runtime validators match the fixed Contract and deterministic generation.");
} else {
  await mkdir(new URL("./", outputUrl), { recursive: true });
  await writeFile(outputUrl, generated, "utf8");
  console.log("Generated self-contained runtime validators: " + Buffer.byteLength(generated) + " bytes.");
}
