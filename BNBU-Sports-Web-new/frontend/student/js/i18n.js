let currentLanguage = "zh";

export function setLanguage(lang) {
  currentLanguage = lang === "en" ? "en" : "zh";
}

export function getLanguage() {
  return currentLanguage;
}

/** stringResource(R.string.key) equivalent. Positional args replace %1$s/%1$d… */
export function t(key, ...args) {
  const entry = STRINGS[key];
  let text = entry ? entry[currentLanguage === "en" ? 1 : 0] : key;
  args.forEach((value, index) => {
    text = text.replaceAll(`%${index + 1}$s`, String(value)).replaceAll(`%${index + 1}$d`, String(value));
  });
  return text;
}

/** interfaceText(中文, English) equivalent for hard-coded bilingual copy. */
export function tx(chinese, english) {
  return currentLanguage === "en" ? english : chinese;
}

/** Locale used for date formatting (AppLanguagePreferences.currentLocale). */
export function currentLocale() {
  return currentLanguage === "en" ? "en-US" : "zh-CN";
}
